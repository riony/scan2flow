"""Deterministic geometry/CFD prototype copied from a working research pipeline.
Inputs and legacy schemas are documented in README.md and MIGRATION.md.
Paths and execution boundaries were adapted; numerical routines remain exploratory.
No capture images or upstream inference are included or required.
Historical thresholds, dimensions and quality heuristics are not generic guarantees.
Do not run against an evidence archive; use disposable copies and explicit outputs.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

CMU = 0.09  # k-omega/k-epsilon model constant

# Project-wide reference defaults (see plan.md §Specifications). A case config may
# override any of these; anything absent falls back here.
DEFAULTS: dict[str, Any] = {
    "reference": {
        "U_mps": 40.0,
        "rho": 1.225,
        "nu": 1.5e-5,
        "pref": 0.0,
        "turbulence_intensity": 0.005,  # 0.5 %
        "turbulence_length_m": 0.1,
        "of_version": "v2512",
    },
    "mesh": {"tool": "snappy", "surface_level": [5, 6], "n_layers": 6, "base_cell_m": 0.7},
    "solve": {
        "tiers": ["RANS", "DDES"],
        "n_cores": 96,
        "rans_end": 3000,
        "ddes_end_s": 2.5,
        "ddes_avg_start_s": 0.5,
        "ddes_write_s": 0.02,
        "ground_type": "moving",
    },
}


def _deep_merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        out[k] = (
            _deep_merge(base[k], v) if isinstance(v, dict) and isinstance(base.get(k), dict) else v
        )
    return out


@dataclass
class CaseConfig:
    raw: dict
    slug: str
    provenance: dict
    geometry: dict
    reference: dict
    mesh: dict
    solve: dict

    # -- derived turbulence inlet quantities -------------------------------
    @property
    def k_inlet(self) -> float:
        U, I = self.reference["U_mps"], self.reference["turbulence_intensity"]
        return 1.5 * (I * U) ** 2

    @property
    def omega_inlet(self) -> float:
        L = self.reference["turbulence_length_m"]
        return math.sqrt(self.k_inlet) / (CMU**0.25 * L)

    @property
    def nut_inlet(self) -> float:
        return self.k_inlet / self.omega_inlet

    @property
    def re_length(self) -> float:
        return self.reference["U_mps"] * self.geometry["length_m"] / self.reference["nu"]

    @property
    def aref(self) -> float:
        """forceCoeffs reference area. Half the frontal area for a half body so the
        reported coefficients equal the full-vehicle values (see templates/README)."""
        A = self.geometry["frontal_area_m2"]
        return A / 2.0 if self.geometry.get("symmetry", "half") == "half" else A

    @property
    def lref(self) -> float:
        return self.geometry.get("wheelbase_m") or self.geometry["length_m"]


def load(path: str | Path) -> CaseConfig:
    cfg = yaml.safe_load(Path(path).read_text())
    merged = _deep_merge(DEFAULTS, {k: cfg.get(k, {}) for k in DEFAULTS})
    return CaseConfig(
        raw=cfg,
        slug=cfg["slug"],
        provenance=cfg.get("provenance", {}),
        geometry=cfg["geometry"],
        reference=merged["reference"],
        mesh=merged["mesh"],
        solve=merged["solve"],
    )


def case_definition(cfg: CaseConfig, tier: str) -> str:
    """Render the ``system/include/caseDefinition`` content for a tier."""
    U = cfg.reference["U_mps"]
    cofr = cfg.geometry.get("cofr") or [0.4 * cfg.geometry["length_m"], 0.0, 0.4]
    lines = [
        "/* Generated by pipeline/config.py — do not edit by hand. */",
        "",
        f"Uinf            {U};",
        f"UinfVec         ({U} 0 0);",
        f"nu              {cfg.reference['nu']:g};",
        f"rhoInf          {cfg.reference['rho']:g};",
        f"pref            {cfg.reference['pref']:g};",
        "",
        f"kInlet          {cfg.k_inlet:.6g};",
        f"omegaInlet      {cfg.omega_inlet:.6g};",
        f"nutInlet        {cfg.nut_inlet:.6g};",
        "",
        f"Aref            {cfg.aref:.6g};",
        f"lRef            {cfg.lref:.6g};",
        f"CofR            ({cofr[0]:g} {cofr[1]:g} {cofr[2]:g});",
        f"groundType      {cfg.solve['ground_type']};",
        f"nCores          {cfg.solve['n_cores']};",
        """carPatches      "(car|body|wheels|mirrors|underbody|glass|.*body.*|.*wheel.*)";""",
    ]
    if tier == "RANS":
        lines += ["", "RASturbModel    kOmegaSST;"]
    else:
        lines += [
            "",
            "LESturbModel    kOmegaSSTDDES;",
            "deltaTurb       maxDeltaxyz;",
            f"dtInit          {cfg.solve.get('ddes_dt', 1e-4):g};",
            f"maxCo           {cfg.solve.get('ddes_maxco', 2.0):g};",
            f"endTime         {cfg.solve['ddes_end_s']:g};",
            f"avgStart        {cfg.solve['ddes_avg_start_s']:g};",
            f"writeIntervalT  {cfg.solve['ddes_write_s']:g};",
        ]
    return "\n".join(lines) + "\n"
